def resolve_lang(request: Request) -> tuple[str, bool]:
    """Returns (language, chosen_explicitly_via_query)."""
    query = request.query_params.get("lang", "").lower()
    if query in LANGS:
        return query, True
    cookie = request.cookies.get("lang", "").lower()
    if cookie in LANGS:
        return cookie, False
    for part in request.headers.get("accept-language", "").split(","):
        code = part.split(";")[0].strip().lower().split("-")[0]
        if code in LANGS:
            return code, False
    return "en", False


def translator(lang: str):
    table = STRINGS.get(lang, STRINGS["en"])
    fallback = STRINGS["en"]

    def t(key: str, **params: object) -> str:
        text = table.get(key) or fallback.get(key) or key
        if params:
            try:
                return text.format(**params)
            except (KeyError, IndexError, ValueError):
                return text
        return text

    return t


def js_strings(lang: str) -> dict[str, str]:
    t = translator(lang)
    return {key: t(key) for key in JS_KEYS}
